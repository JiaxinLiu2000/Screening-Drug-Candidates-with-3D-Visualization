"""Task 6 - assemble results/SUMMARY.md with the four proposal numbers.

Reads only committed artefacts produced by scripts 02-05; computes nothing new,
so the printed numbers and the file are guaranteed to agree.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tox21lib import paths  # noqa: E402


def require(path: Path) -> Path:
    if not path.exists():
        raise SystemExit(f"FAILED: {path} missing - run the earlier scripts first")
    return path


def main() -> int:
    std = json.loads(
        require(paths.RESULTS / "standardization_stats.json").read_text(encoding="utf-8")
    )
    scaf = json.loads(
        require(paths.RESULTS / "scaffold_stats.json").read_text(encoding="utf-8")
    )
    egfr = json.loads(
        require(paths.RESULTS / "egfr_structures.json").read_text(encoding="utf-8")
    )
    summary = pd.read_csv(require(paths.RESULTS / "baseline_summary.csv"))
    metrics = pd.read_csv(require(paths.RESULTS / "baseline_metrics.csv"))

    overall = summary[summary["level"] == "overall"].set_index("split")
    n_mols = std["final_molecules"]
    rnd = overall.loc["random"]
    scf = overall.loc["scaffold"]
    rec = egfr["recommendation"]

    per_endpoint = summary[summary["level"] == "endpoint"].pivot(
        index="endpoint", columns="split", values=["roc_auc_mean", "roc_auc_std",
                                                   "pr_auc_mean", "pr_auc_std"]
    )

    lines: list[str] = []
    add = lines.append
    add("# Preliminary results - multi-objective virtual screening (Tox21 + EGFR)")
    add("")
    add("Generated by `src/06_summary.py` from the committed artefacts in `results/`,")
    add("`splits/` and `receptors/`. Every number below is measured, not estimated.")
    add("")
    add("## The four requested values")
    add("")
    add(f"**1. Molecules in Tox21 after standardization and deduplication: {n_mols}**")
    add("")
    add(f"   {std['input_rows']} merged rows -> {std['parse_failures']} unparsable dropped")
    add(f"   -> {std['duplicate_rows_merged']} duplicate rows merged on InChIKey")
    add(f"   ({std['unique_inchikeys']} unique keys) -> {std['filtered_out']} removed by the")
    add(f"   10-60 heavy-atom / element filter -> **{n_mols}** molecules.")
    add("")
    add("**2. Mean ROC-AUC across the 12 endpoints, random split "
        f"(mean +/- std over 5 seeds): {rnd['roc_auc_mean']:.4f} +/- {rnd['roc_auc_std']:.4f}**")
    add("")
    add("**3. Mean ROC-AUC across the 12 endpoints, scaffold split "
        f"(mean +/- std over 5 seeds): {scf['roc_auc_mean']:.4f} +/- {scf['roc_auc_std']:.4f}**")
    add("")
    add(f"   Scaffold-split penalty: {rnd['roc_auc_mean'] - scf['roc_auc_mean']:.4f} ROC-AUC.")
    add(f"   PR-AUC for reference: random {rnd['pr_auc_mean']:.4f} +/- {rnd['pr_auc_std']:.4f}, "
        f"scaffold {scf['pr_auc_mean']:.4f} +/- {scf['pr_auc_std']:.4f}.")
    add("")
    add(f"**4. PDB ID to use: {rec['recommended']}** (over {rec['runner_up']})")
    add("")
    add(f"   {rec['reason']}")
    add("")
    add("## How these were produced")
    add("")
    add(f"- Baseline: Morgan r=2, 2048 bits -> RandomForestClassifier(500 trees, "
        f"class_weight='balanced'), one model per endpoint, "
        f"{len(metrics)} (split, seed, endpoint) fits total.")
    add("- The seed (0-4) controls both the split and the forest; splits are replayed from "
        "the committed index files in `splits/`.")
    add(f"- Scaffold split: {scaf['n_unique_scaffolds']} unique Bemis-Murcko scaffolds, "
        f"largest group {scaf['largest_group_size']} molecules "
        f"(`{scaf['largest_group_scaffold'] or 'acyclic'}`), "
        f"{scaf['n_singleton_scaffolds']} singletons; whole groups never split.")
    add("")
    add("## Per-endpoint ROC-AUC (mean +/- std over 5 seeds)")
    add("")
    add("| endpoint | random | scaffold | delta |")
    add("| --- | --- | --- | --- |")
    for endpoint in per_endpoint.index:
        r_m = per_endpoint.loc[endpoint, ("roc_auc_mean", "random")]
        r_s = per_endpoint.loc[endpoint, ("roc_auc_std", "random")]
        s_m = per_endpoint.loc[endpoint, ("roc_auc_mean", "scaffold")]
        s_s = per_endpoint.loc[endpoint, ("roc_auc_std", "scaffold")]
        add(f"| {endpoint} | {r_m:.4f} +/- {r_s:.4f} | {s_m:.4f} +/- {s_s:.4f} "
            f"| {r_m - s_m:+.4f} |")
    add(f"| **macro avg (12)** | **{rnd['roc_auc_mean']:.4f} +/- {rnd['roc_auc_std']:.4f}** "
        f"| **{scf['roc_auc_mean']:.4f} +/- {scf['roc_auc_std']:.4f}** "
        f"| **{rnd['roc_auc_mean'] - scf['roc_auc_mean']:+.4f}** |")
    add("")
    add("## EGFR structures")
    add("")
    add("| PDB | resolution (A) | chains | ligand (atoms) | waters | kept chain residues "
        "| residues within 5 A |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for s in egfr["structures"]:
        add(f"| {s['pdb_id']} | {s['resolution']} | {','.join(s['chains_in_model'])} "
            f"| {s['ligand']['resname']} ({s['ligand']['n_atoms']}) "
            f"| {s['n_water_molecules']} | {s['kept_chain_n_residues']} "
            f"| {s['n_contact_residues']} |")
    add("")
    add("Pocket centers (ligand centroid, A): "
        + "; ".join(f"{s['pdb_id']} {s['pocket_center']}" for s in egfr["structures"]))
    add("")
    add("Viewer: open `figures/viewer.html` directly in a browser (no server needed).")
    add("")

    text = "\n".join(lines)
    out = paths.RESULTS / "SUMMARY.md"
    out.write_text(text, encoding="utf-8")
    print(text)
    print(f"[wrote {out}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
