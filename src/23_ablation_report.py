"""Phase 3 Task 5 (reporting) - results/shared_encoder_ablation.md.

Reads `results/shared_encoder_metrics.csv` (written by
`src/20_shared_encoder_ablation.py`) and the random-forest floors, aggregates
mean +/- sample std over seeds, and states which of the three shared-encoder
outcomes the numbers support. Nothing is recomputed or estimated here.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tox21lib import paths  # noqa: E402

METRICS = paths.RESULTS / "shared_encoder_metrics.csv"
CONFIG_LABEL = {
    "A": "A — GIN from scratch, toxicity only",
    "B": "B — GIN from scratch, affinity only",
    "C": "C — GIN from scratch, both tasks (shared encoder)",
    "D": "D — ChemBERTa fine-tuned, both tasks (shared encoder)",
    "E": "E — ChemBERTa fine-tuned, toxicity only (pretrained control)",
    "F": "F — ChemBERTa fine-tuned, affinity only (pretrained control)",
}


def ms(values: pd.Series) -> str:
    v = values.dropna()
    if v.empty:
        return "—"
    if len(v) == 1:
        return f"{v.iloc[0]:.4f}"
    return f"{v.mean():.4f} ± {v.std(ddof=1):.4f}"


def mean_or_nan(values: pd.Series) -> float:
    v = values.dropna()
    return float(v.mean()) if not v.empty else float("nan")


def main() -> int:
    if not METRICS.exists():
        raise SystemExit(f"FAILED: {METRICS} missing - run src/20_shared_encoder_ablation.py")
    m = pd.read_csv(METRICS)
    main_cells = m[(m["loss_weight"].isna()) | (m["loss_weight"] == 1.0)]

    # Random-forest floors on the same folds.
    summary = pd.read_csv(paths.RESULTS / "baseline_summary.csv")
    rf_tox = summary[
        (summary["dataset"] == "Tox21") & (summary["level"] == "overall")
        & (summary["split"] == "scaffold")
    ].iloc[0]
    rf_bind = pd.read_csv(paths.RESULTS / "binding_baseline.csv")
    rf_bind = rf_bind[rf_bind["dataset"] == "KIBA"]

    L: list[str] = []
    add = L.append
    add("# Shared-encoder ablation (Phase 3, Task 5)")
    add("")
    add("Toxicity is measured on the committed Tox21 **scaffold** split; affinity on "
        "the committed KIBA **random / cold_drug / cold_target** splits — the same "
        "index files the random forests used, so the RF numbers below are a "
        "like-for-like floor rather than a different experiment. `±` is the sample "
        "standard deviation over seeds (ddof = 1). Generated by "
        "`src/23_ablation_report.py` from `results/shared_encoder_metrics.csv`.")
    add("")
    add("| config | encoder | tasks | parameters |")
    add("| --- | --- | --- | --- |")
    for cfg in sorted(m["config"].unique()):
        sub = m[m["config"] == cfg].iloc[0]
        add(f"| {cfg} | {sub['encoder']} | {sub['tasks']} | "
            f"{int(sub['n_parameters']):,} |")
    add("")

    add("## Toxicity (Tox21 scaffold split)")
    add("")
    add("| config | macro ROC-AUC | macro PR-AUC | seeds |")
    add("| --- | --- | --- | --- |")
    tox_rows = main_cells[main_cells["tox_macro_roc_auc"].notna()]
    tox_means: dict[str, float] = {}
    for cfg in sorted(tox_rows["config"].unique()):
        sub = tox_rows[tox_rows["config"] == cfg]
        # C and D appear once per affinity split; the toxicity fold is the same, so
        # all of their runs are pooled here and the count is stated.
        tox_means[cfg] = mean_or_nan(sub["tox_macro_roc_auc"])
        add(f"| {cfg} | {ms(sub['tox_macro_roc_auc'])} | {ms(sub['tox_macro_pr_auc'])} "
            f"| {len(sub)} |")
    add(f"| **random forest (floor)** | **{rf_tox['roc_auc_mean']:.4f} ± "
        f"{rf_tox['roc_auc_std']:.4f}** | **{rf_tox['pr_auc_mean']:.4f} ± "
        f"{rf_tox['pr_auc_std']:.4f}** | 5 |")
    add("")

    add("## Affinity (KIBA)")
    add("")
    add("| config | split | RMSE | Pearson r | Spearman rho | CI |")
    add("| --- | --- | --- | --- | --- | --- |")
    aff_rows = main_cells[main_cells["affinity_rmse"].notna()]
    aff_means: dict[tuple[str, str], float] = {}
    for cfg in sorted(aff_rows["config"].unique()):
        for split in ("random", "cold_drug", "cold_target"):
            sub = aff_rows[(aff_rows["config"] == cfg) & (aff_rows["affinity_split"] == split)]
            if sub.empty:
                continue
            aff_means[(cfg, split)] = mean_or_nan(sub["affinity_pearson_r"])
            add(f"| {cfg} | {split} | {ms(sub['affinity_rmse'])} "
                f"| {ms(sub['affinity_pearson_r'])} | {ms(sub['affinity_spearman_rho'])} "
                f"| {ms(sub['affinity_ci'])} |")
    for split in ("random", "cold_drug", "cold_target"):
        sub = rf_bind[rf_bind["split"] == split]
        add(f"| **random forest (floor)** | {split} | **{ms(sub['rmse'])}** "
            f"| **{ms(sub['pearson_r'])}** | **{ms(sub['spearman_rho'])}** "
            f"| **{ms(sub['ci'])}** |")
    add("")

    add("## Loss-weight grid (configurations C and D, random affinity split)")
    add("")
    add("The full grid is reported, not only the best cell. The weight multiplies the "
        "affinity loss relative to the toxicity loss.")
    add("")
    sweep = m[(m["config"].isin(["C", "D"])) & (m["affinity_split"] == "random")
              & m["loss_weight"].notna()]
    add("| config | loss weight | tox macro ROC-AUC | affinity Pearson r | affinity RMSE | seeds |")
    add("| --- | --- | --- | --- | --- | --- |")
    for cfg in ("C", "D"):
        for weight in sorted(sweep["loss_weight"].unique()):
            sub = sweep[(sweep["config"] == cfg) & (sweep["loss_weight"] == weight)]
            if sub.empty:
                continue
            add(f"| {cfg} | {weight:g} | {ms(sub['tox_macro_roc_auc'])} "
                f"| {ms(sub['affinity_pearson_r'])} | {ms(sub['affinity_rmse'])} "
                f"| {len(sub)} |")
    add("")

    # ---- verdict -----------------------------------------------------------
    a = tox_means.get("A", float("nan"))
    c_tox = tox_means.get("C", float("nan"))
    d_tox = tox_means.get("D", float("nan"))
    e_tox = tox_means.get("E", float("nan"))
    b_aff = aff_means.get(("B", "random"), float("nan"))
    c_aff = aff_means.get(("C", "random"), float("nan"))
    d_aff = aff_means.get(("D", "random"), float("nan"))
    f_aff = aff_means.get(("F", "random"), float("nan"))

    def seed_std(cfg: str, column: str, split: str | None = None) -> float:
        sub = main_cells[main_cells["config"] == cfg]
        if split:
            sub = sub[sub["affinity_split"] == split]
        v = sub[column].dropna()
        return float(v.std(ddof=1)) if len(v) > 1 else float("nan")

    tox_noise = np.nanmax([seed_std("A", "tox_macro_roc_auc"),
                           seed_std("C", "tox_macro_roc_auc")])
    aff_noise = np.nanmax([seed_std("B", "affinity_pearson_r", "random"),
                           seed_std("C", "affinity_pearson_r", "random")])

    # The sweep is part of the evidence, not decoration: at weight 1 the shared GIN
    # is clearly worse, but the best-weight cell is a different claim. Judging only
    # the default weight would report "sharing hurts" when the honest statement is
    # "sharing at weight 1 hurts; tuned, it is neutral".
    def best_cell(cfg: str, column: str, higher_better: bool = True):
        sub = sweep[sweep["config"] == cfg]
        if sub.empty:
            return float("nan"), float("nan"), 0
        grouped = sub.groupby("loss_weight")[column].agg(["mean", "size"])
        grouped = grouped.dropna()
        if grouped.empty:
            return float("nan"), float("nan"), 0
        row = grouped["mean"].idxmax() if higher_better else grouped["mean"].idxmin()
        return float(grouped.loc[row, "mean"]), float(row), int(grouped.loc[row, "size"])

    c_tox_best, c_tox_w, c_tox_n = best_cell("C", "tox_macro_roc_auc")
    c_aff_best, c_aff_w, c_aff_n = best_cell("C", "affinity_pearson_r")
    d_tox_best, d_tox_w, d_tox_n = best_cell("D", "tox_macro_roc_auc")
    d_aff_best, d_aff_w, d_aff_n = best_cell("D", "affinity_pearson_r")

    shared_helps_tox = max(c_tox - a, c_tox_best - a) > tox_noise
    shared_helps_aff = max(c_aff - b_aff, c_aff_best - b_aff) > aff_noise
    pretrained_shared_helps_tox = (
        max(d_tox - e_tox, d_tox_best - e_tox) > tox_noise
        if not np.isnan(e_tox) else False
    )
    pretrained_shared_helps_aff = (
        max(d_aff - f_aff, d_aff_best - f_aff) > aff_noise
        if not np.isnan(f_aff) else False
    )

    hurts_at_default = (a - c_tox) > tox_noise or (b_aff - c_aff) > aff_noise
    neutral_when_tuned = (
        abs(c_tox_best - a) <= tox_noise and abs(c_aff_best - b_aff) <= aff_noise
    )

    if shared_helps_tox or shared_helps_aff:
        verdict = "shared encoding helps regardless of pretraining"
    elif pretrained_shared_helps_tox or pretrained_shared_helps_aff:
        verdict = "shared encoding helps only when the encoder is pretrained"
    else:
        verdict = ("shared encoding does not help, and the chemical-space "
                   "measurement explains why")

    chem = json.loads(
        (paths.RESULTS / "chemical_space_overlap_kiba.json").read_text(encoding="utf-8")
    )
    nn = chem["nn_tanimoto"]

    add("## Verdict")
    add("")
    add(f"**{verdict}.**")
    add("")
    add("| comparison | toxicity macro ROC-AUC | affinity Pearson r (random split) |")
    add("| --- | --- | --- |")
    add(f"| single-task, from scratch (A / B) | {a:.4f} | {b_aff:.4f} |")
    add(f"| shared, from scratch (C) | {c_tox:.4f} | {c_aff:.4f} |")
    if not np.isnan(e_tox) or not np.isnan(f_aff):
        add(f"| single-task, pretrained (E / F) | "
            f"{e_tox:.4f} | {f_aff:.4f} |")
    add(f"| shared, pretrained (D) | {d_tox:.4f} | {d_aff:.4f} |")
    add(f"| **effect of sharing, from scratch (C − A / C − B)** | "
        f"**{c_tox - a:+.4f}** | **{c_aff - b_aff:+.4f}** |")
    if not np.isnan(e_tox):
        add(f"| **effect of sharing, pretrained (D − E / D − F)** | "
            f"**{d_tox - e_tox:+.4f}** | **{d_aff - f_aff:+.4f}** |")
    add(f"| shared, from scratch, best loss weight (C @ w={c_tox_w:g} / "
        f"w={c_aff_w:g}) | {c_tox_best:.4f} | {c_aff_best:.4f} |")
    add(f"| **effect of sharing at the best weight (C − A / C − B)** | "
        f"**{c_tox_best - a:+.4f}** | **{c_aff_best - b_aff:+.4f}** |")
    add("")
    add(f"Largest seed-to-seed standard deviation used as the noise floor: "
        f"{tox_noise:.4f} (toxicity macro ROC-AUC), {aff_noise:.4f} (affinity "
        f"Pearson r). A difference is only called an effect if it exceeds that.")
    add("")
    add(f"**The default loss weight is doing most of the damage.** At weight 1 the "
        f"shared GIN is clearly worse than single-task ({c_tox - a:+.4f} toxicity, "
        f"{c_aff - b_aff:+.4f} affinity), but its best sweep cells reach "
        f"{c_tox_best:.4f} toxicity (w={c_tox_w:g}, {c_tox_n} seeds) and "
        f"{c_aff_best:.4f} affinity Pearson (w={c_aff_w:g}, {c_aff_n} seeds), both "
        f"within the seed noise of the single-task configurations. The accurate "
        f"statement is therefore: sharing at the default weight hurts; with the "
        f"weight tuned down it is neutral; at no weight does it beat single-task "
        f"training by more than seed noise. Sweep cells use fewer seeds than the "
        f"main comparison, so they are the weaker evidence of the two."
        if hurts_at_default and neutral_when_tuned else
        f"Best sweep cells: C reaches {c_tox_best:.4f} toxicity (w={c_tox_w:g}) and "
        f"{c_aff_best:.4f} affinity Pearson (w={c_aff_w:g}).")
    add("")
    add(f"Chemical-space context (Task 1): the median nearest-neighbour Tanimoto from "
        f"Tox21 to KIBA is {nn['tox21_to_kiba']['median']:.4f} against within-set "
        f"medians of {nn['within_tox21']['median']:.4f} (Tox21) and "
        f"{nn['within_kiba']['median']:.4f} (KIBA) — "
        f"**{chem['verdict'].lower()}**. The two task datasets are adjacent rather "
        f"than overlapping, which is the condition this ablation was restructured to "
        f"test.")
    add("")
    add("Configurations E and F exist because D alone changes two things at once "
        "(pretrained encoder *and* task sharing); without a pretrained single-task "
        "control, 'pretraining helps' cannot be told apart from 'sharing helps when "
        "pretrained'.")
    add("")

    text = "\n".join(L) + "\n"
    (paths.RESULTS / "shared_encoder_ablation.md").write_text(text, encoding="utf-8")
    (paths.RESULTS / "shared_encoder_ablation.json").write_text(
        json.dumps(
            {
                "verdict": verdict,
                "toxicity_macro_roc_auc": tox_means,
                "affinity_pearson_random": {f"{k[0]}": v for k, v in aff_means.items()
                                            if k[1] == "random"},
                "effect_of_sharing_scratch_tox": c_tox - a,
                "effect_of_sharing_scratch_affinity": c_aff - b_aff,
                "effect_of_sharing_pretrained_tox": d_tox - e_tox,
                "effect_of_sharing_pretrained_affinity": d_aff - f_aff,
                "best_weight_cells": {
                    "C_tox": {"value": c_tox_best, "loss_weight": c_tox_w,
                              "seeds": c_tox_n},
                    "C_affinity": {"value": c_aff_best, "loss_weight": c_aff_w,
                                   "seeds": c_aff_n},
                    "D_tox": {"value": d_tox_best, "loss_weight": d_tox_w,
                              "seeds": d_tox_n},
                    "D_affinity": {"value": d_aff_best, "loss_weight": d_aff_w,
                                   "seeds": d_aff_n},
                },
                "effect_of_sharing_best_weight_tox": c_tox_best - a,
                "effect_of_sharing_best_weight_affinity": c_aff_best - b_aff,
                "hurts_at_default_weight": bool(hurts_at_default),
                "neutral_when_tuned": bool(neutral_when_tuned),
                "tox_noise_floor": float(tox_noise),
                "affinity_noise_floor": float(aff_noise),
                "rf_tox_macro_roc_auc": float(rf_tox["roc_auc_mean"]),
                "n_runs": int(len(m)),
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(text)
    print(f"[wrote results/shared_encoder_ablation.md from {len(m)} runs]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
