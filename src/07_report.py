"""Generate RESULTS.md - one document with every measured number in the project.

Reads only the committed artefacts written by scripts 01-06, so the document can
never disagree with the CSV/JSON tables it summarizes. Nothing is recomputed and
nothing is estimated.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tox21lib import featurize, paths, standardize  # noqa: E402


def require(path: Path) -> Path:
    if not path.exists():
        raise SystemExit(f"FAILED: {path} missing - run the earlier scripts first")
    return path


def load_json(path: Path) -> dict:
    return json.loads(require(path).read_text(encoding="utf-8"))


def table(df: pd.DataFrame, floatfmt: str = "{:.4f}") -> list[str]:
    """Render a DataFrame as a GitHub markdown table."""
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    rule = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = []
    for _, r in df.iterrows():
        cells = [
            floatfmt.format(v) if isinstance(v, float) else str(v)
            for v in r.tolist()
        ]
        rows.append("| " + " | ".join(cells) + " |")
    return [header, rule, *rows]


def pretty(text: str) -> str:
    """Render the ASCII-safe strings from the pipeline for a markdown document.

    The scripts keep Angstrom/alpha out of stdout because a Windows console in
    cp1252 cannot encode them; this document is UTF-8, so restore them here.
    """
    return (
        text.replace("alphaC", "\u03b1C")
        .replace(" A pocket", " \u00c5 pocket")
        .replace(" A (", " \u00c5 (")
        .replace(" A,", " \u00c5,")
        .replace(" A ", " \u00c5 ")
        .replace(" A.", " \u00c5.")
    )



def environment() -> list[str]:
    """Interpreter and the versions actually imported during the run."""
    import numpy
    import sklearn

    import rdkit

    rows = [
        ("python", sys.version.split()[0]),
        ("rdkit", rdkit.__version__),
        ("scikit-learn", sklearn.__version__),
        ("pandas", pd.__version__),
        ("numpy", numpy.__version__),
    ]
    try:
        import tdc

        rows.append(("PyTDC", getattr(tdc, "__version__", "0.4.1")))
    except Exception:  # noqa: BLE001 - optional at report time
        pass
    try:
        import gemmi

        rows.append(("gemmi", gemmi.__version__))
    except Exception:  # noqa: BLE001
        pass
    return [f"`{name} {version}`" for name, version in rows]


def git_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=paths.ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip()
    except Exception:  # noqa: BLE001 - report must not depend on git
        return "n/a"


def main() -> int:
    std = load_json(paths.RESULTS / "standardization_stats.json")
    scaf = load_json(paths.RESULTS / "scaffold_stats.json")
    egfr = load_json(paths.RESULTS / "egfr_structures.json")
    raw_stats = pd.read_csv(require(paths.RESULTS / "tox21_endpoint_stats.csv"))
    clean_stats = pd.read_csv(require(paths.RESULTS / "clean_endpoint_stats.csv"))
    sizes = pd.read_csv(require(paths.RESULTS / "split_sizes.csv"))
    overlap = pd.read_csv(require(paths.RESULTS / "split_seed_overlap.csv"))
    metrics = pd.read_csv(require(paths.RESULTS / "baseline_metrics.csv"))
    summary = pd.read_csv(require(paths.RESULTS / "baseline_summary.csv"))

    overall = summary[summary["level"] == "overall"].set_index("split")
    rnd, scf_row = overall.loc["random"], overall.loc["scaffold"]
    rec = egfr["recommendation"]
    per_endpoint = summary[summary["level"] == "endpoint"]

    L: list[str] = []
    add = L.append

    add("# Preliminary results — multi-objective virtual screening (Tox21 + EGFR)")
    add("")
    add("CS 6140 final-project proposal. Every number in this document was measured by "
        "the pipeline in `src/`; none is estimated, illustrative or placeholder. "
        "Generated by `src/07_report.py` from the committed artefacts in `results/`, "
        "`splits/` and `receptors/`.")
    add("")
    add(f"- commit: `{git_commit()}`")
    add("- environment: " + ", ".join(environment()))
    add(f"- seeds: {list(paths.SEEDS)} (each seed controls both the split and the forest)")
    add("")
    add("---")
    add("")
    add("## 1. The four requested values")
    add("")
    add("| # | value | result |")
    add("| --- | --- | --- |")
    add(f"| 1 | Molecules after standardization + deduplication | **{std['final_molecules']}** |")
    add(f"| 2 | Mean ROC-AUC over 12 endpoints, **random** split | "
        f"**{rnd['roc_auc_mean']:.4f} ± {rnd['roc_auc_std']:.4f}** |")
    add(f"| 3 | Mean ROC-AUC over 12 endpoints, **scaffold** split | "
        f"**{scf_row['roc_auc_mean']:.4f} ± {scf_row['roc_auc_std']:.4f}** |")
    add(f"| 4 | Receptor to use | **{rec['recommended']}** (over {rec['runner_up']}) |")
    add("")
    add(f"Scaffold-split penalty: **{rnd['roc_auc_mean'] - scf_row['roc_auc_mean']:.4f}** "
        f"ROC-AUC. PR-AUC: random {rnd['pr_auc_mean']:.4f} ± {rnd['pr_auc_std']:.4f}, "
        f"scaffold {scf_row['pr_auc_mean']:.4f} ± {scf_row['pr_auc_std']:.4f}.")
    add("")
    add("`±` is the **sample standard deviation over the 5 seeds** (pandas `.std()`, "
        "ddof = 1, n = 5) of the per-seed macro average across the 12 endpoints — "
        "seed-to-seed variability, not endpoint spread.")
    add("")
    add("---")
    add("")
    add("## 2. Dataset — Tox21 via TDC")
    add("")
    n_endpoints = len(raw_stats)
    n_molecules = int(raw_stats["n_tested"].iloc[0] + raw_stats["n_missing"].iloc[0])
    add(f"Endpoint names come from `tdc.utils.retrieve_label_name_list(\"Tox21\")` "
        f"({n_endpoints} names, not hardcoded); each endpoint is a separate "
        "`tdc.single_pred.Tox` dataset, outer-joined on `(Drug_ID, SMILES)`.")
    add("")
    add(f"**Merged wide table shape: `({n_molecules}, {n_endpoints + 2})`** — "
        f"{n_molecules} molecules × (`drug_id`, `smiles` + {n_endpoints} label columns), "
        "NaN where a compound was not tested on that endpoint.")
    add("")
    add("### Per-endpoint coverage and positive rate (merged table)")
    add("")
    L.extend(table(raw_stats))
    add("")
    add("---")
    add("")
    add("## 3. Standardization and deduplication")
    add("")
    add("Per SMILES: parse → largest covalently connected fragment (salt strip) → "
        "`Chem.RemoveStereochemistry` → canonical SMILES → InChIKey. "
        "Deduplication on InChIKey with a per-label majority vote; ties become NaN. "
        f"Filter: {standardize.MIN_HEAVY_ATOMS}–{standardize.MAX_HEAVY_ATOMS} heavy atoms "
        "and elements " + "{" + ", ".join(sorted(standardize.ALLOWED_ELEMENTS)) + "}.")
    add("")
    add("| step | count |")
    add("| --- | --- |")
    add(f"| merged input rows | {std['input_rows']} |")
    add(f"| dropped, failed to parse | {std['parse_failures']} "
        f"({', '.join(f'{k}={v}' for k, v in std['parse_failure_breakdown'].items())}) |")
    add(f"| rows entering deduplication | {std['rows_before_dedup']} |")
    add(f"| unique InChIKeys | {std['unique_inchikeys']} |")
    add(f"| **duplicate rows merged** | **{std['duplicate_rows_merged']}** |")
    add(f"| label cells set to NaN by a tied vote | {std['label_cells_nan_from_tie']} |")
    add(f"| **removed by heavy-atom / element filter** | **{std['filtered_out']}** "
        f"({', '.join(f'{k}={v}' for k, v in std['filter_breakdown'].items())}) |")
    add(f"| **final molecules** | **{std['final_molecules']}** |")
    add("")
    add("**v1 simplification:** stereochemistry is removed before the InChIKey is "
        "computed, so enantiomers and cis/trans pairs collapse to one record. The model "
        "therefore cannot express stereo-dependent toxicity; restoring stereo is the "
        "first planned change after the proposal.")
    add("")
    add("### Per-endpoint labels after cleaning")
    add("")
    L.extend(table(clean_stats))
    add("")
    add("---")
    add("")
    add("## 4. Splits (computed once, before any featurization)")
    add("")
    add("| statistic | value |")
    add("| --- | --- |")
    add(f"| unique Bemis-Murcko scaffolds | **{scaf['n_unique_scaffolds']}** |")
    add(f"| largest scaffold group | **{scaf['largest_group_size']}** molecules "
        f"(`{scaf['largest_group_scaffold'] or 'acyclic'}`) |")
    add(f"| singleton scaffolds | {scaf['n_singleton_scaffolds']} |")
    add(f"| acyclic molecules (empty scaffold, one group) | {scaf['n_acyclic_molecules']} |")
    add("")
    add("### Split sizes and scaffold leakage")
    add("")
    add("`scaffold_groups_spanning_subsets` is computed for **both** splits. A large "
        "count for the random split is the expected leakage; the scaffold split must be "
        "exactly 0, and `03_splits.py` fails the run if either condition breaks.")
    add("")
    L.extend(table(sizes))
    add("")
    add("### Test-set overlap between seeds (same split)")
    add("")
    agg = (
        overlap.groupby("split")[["n_shared_test", "jaccard"]]
        .agg(["min", "mean", "max"])
        .round(4)
    )
    agg.columns = [f"{a}_{b}" for a, b in agg.columns]
    L.extend(table(agg.reset_index()))
    add("")
    add("Scaffold-split test sets are genuinely different across seeds (Jaccard well "
        "below 1), so the ± spread is not forest noise alone. The seed permutes only "
        "the order of *equal-sized* scaffold groups, so the required size-descending "
        "ordering is preserved.")
    add("")
    add("---")
    add("")
    add("## 5. Random-forest baseline")
    add("")
    add(f"Morgan fingerprints, radius {featurize.MORGAN_RADIUS}, "
        f"{featurize.MORGAN_N_BITS} bits, from "
        "`rdFingerprintGenerator.GetMorganGenerator` (not the deprecated "
        "`GetMorganFingerprintAsBitVect`). "
        "`RandomForestClassifier(n_estimators=500, class_weight=\"balanced\", "
        "n_jobs=-1, random_state=seed)`, one independent model per endpoint, trained on "
        "training rows with a non-null label and evaluated on test rows with a non-null "
        f"label. 2 splits × {len(paths.SEEDS)} seeds × 12 endpoints = "
        f"**{len(metrics)} fits**.")
    add("")
    add("### ROC-AUC per endpoint (mean ± std over 5 seeds)")
    add("")
    pivot = per_endpoint.pivot(index="endpoint", columns="split",
                              values=["roc_auc_mean", "roc_auc_std"])
    add("| endpoint | random | scaffold | delta (scaffold - random) |")
    add("| --- | --- | --- | --- |")
    for ep in pivot.index:
        rm = pivot.loc[ep, ("roc_auc_mean", "random")]
        rs = pivot.loc[ep, ("roc_auc_std", "random")]
        sm = pivot.loc[ep, ("roc_auc_mean", "scaffold")]
        ss = pivot.loc[ep, ("roc_auc_std", "scaffold")]
        add(f"| {ep} | {rm:.4f} ± {rs:.4f} | {sm:.4f} ± {ss:.4f} | {sm - rm:+.4f} |")
    add(f"| **macro avg (12)** | **{rnd['roc_auc_mean']:.4f} ± {rnd['roc_auc_std']:.4f}** "
        f"| **{scf_row['roc_auc_mean']:.4f} ± {scf_row['roc_auc_std']:.4f}** "
        f"| **{scf_row['roc_auc_mean'] - rnd['roc_auc_mean']:+.4f}** |")
    add("")
    add("### PR-AUC per endpoint (mean ± std over 5 seeds)")
    add("")
    pivot_pr = per_endpoint.pivot(index="endpoint", columns="split",
                                  values=["pr_auc_mean", "pr_auc_std"])
    add("| endpoint | random | scaffold | delta (scaffold - random) "
        "| test positives (random, seed 0) |")
    add("| --- | --- | --- | --- | --- |")
    seed0 = metrics[(metrics["split"] == "random") & (metrics["seed"] == 0)].set_index("endpoint")
    for ep in pivot_pr.index:
        rm = pivot_pr.loc[ep, ("pr_auc_mean", "random")]
        rs = pivot_pr.loc[ep, ("pr_auc_std", "random")]
        sm = pivot_pr.loc[ep, ("pr_auc_mean", "scaffold")]
        ss = pivot_pr.loc[ep, ("pr_auc_std", "scaffold")]
        n_pos = int(seed0.loc[ep, "n_test_pos"])
        n_test = int(seed0.loc[ep, "n_test"])
        add(f"| {ep} | {rm:.4f} ± {rs:.4f} | {sm:.4f} ± {ss:.4f} | {sm - rm:+.4f} "
            f"| {n_pos}/{n_test} ({n_pos / n_test:.1%}) |")
    add(f"| **macro avg (12)** | **{rnd['pr_auc_mean']:.4f} ± {rnd['pr_auc_std']:.4f}** "
        f"| **{scf_row['pr_auc_mean']:.4f} ± {scf_row['pr_auc_std']:.4f}** "
        f"| **{scf_row['pr_auc_mean'] - rnd['pr_auc_mean']:+.4f}** | |")
    add("")
    add("### Per-seed macro averages")
    add("")
    per_seed = (
        metrics.groupby(["split", "seed"])[["roc_auc", "pr_auc"]].mean().round(4).reset_index()
    )
    L.extend(table(per_seed))
    add("")
    add("Full detail: `results/baseline_metrics.csv` "
        f"({len(metrics)} rows, with fold sizes and positive counts) and "
        "`results/baseline_summary.csv`.")
    add("")
    add("---")
    add("")
    add("## 6. EGFR structures")
    add("")
    add("| PDB | resolution | chains | HETATM codes (atoms) | drug-like ligand | waters "
        "| kept chain | residues ≤ 5 Å |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for s in egfr["structures"]:
        het = ", ".join(f"{k} ({v})" for k, v in s["het_atom_counts"].items())
        add(f"| {s['pdb_id']} | {s['resolution']} Å | {','.join(s['chains_in_model'])} "
            f"| {het} | **{s['ligand']['resname']}** ({s['ligand']['n_atoms']} atoms, "
            f"chain {s['ligand']['chain']}, resi {s['ligand']['seqid']}) "
            f"| {s['n_water_molecules']} | {s['kept_chain']} "
            f"({s['kept_chain_n_residues']} res) | {s['n_contact_residues']} |")
    add("")
    add("The ligand is selected as the largest HETATM group that is not water, buffer, "
        "cryoprotectant, ion or unknown and has ≥ 10 atoms — `AQ4` is not hardcoded.")
    add("")
    add("### Pocket geometry (ligand centroid; bounding box + 5 Å per side)")
    add("")
    add("| PDB | center (x, y, z) | box min | box max | box size |")
    add("| --- | --- | --- | --- | --- |")
    for s in egfr["structures"]:
        pocket = load_json(paths.RECEPTORS / f"{s['pdb_id']}_pocket.json")
        add(f"| {s['pdb_id']} | {pocket['center']} | {pocket['box_min']} "
            f"| {pocket['box_max']} | {pocket['box_size']} |")
    add("")
    add("### Residues within 5 Å of the ligand")
    add("")
    for s in egfr["structures"]:
        add(f"- **{s['pdb_id']}** ({s['n_contact_residues']}): "
            + ", ".join(s["contact_residues"]))
    add("")
    add("### Which receptor to use — evidence")
    add("")
    add("Decision criteria, in order: " + pretty("; ".join(rec["criteria"])) + ".")
    add("")
    add("| PDB | deposited TITLE | primary citation | Lys721–Glu738 | state "
        "| unobserved residues in pocket | altloc atoms in pocket | mean B pocket / ligand "
        "| internal chain gaps |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for s in egfr["structures"]:
        q, c, h = s["pocket_quality"], s["conformation"], s["header"]
        add(f"| {s['pdb_id']} | {h['title']} | {h['citation_title']} "
            f"[{h['citation_ref']}] | {c['distance_angstrom']} Å | {pretty(c['state'])} "
            f"| {q['missing_in_pocket'] or 'none'} | {q['altloc_atoms_in_pocket']} "
            f"| {q['mean_b_pocket']} / {q['mean_b_ligand']} "
            f"| {q['n_internal_gap_residues']} {q['internal_gap_residues']} |")
    add("")
    add(f"**Recommendation: {rec['recommended']}.** {pretty(rec['reason'])}")
    add("")
    add("Files per structure: `receptors/<ID>_receptor.pdb` (main protein chain only), "
        "`receptors/<ID>_ligand.sdf` (experimental coordinates), "
        "`receptors/<ID>_pocket.json` (center, box, contact residues with distances).")
    add("")
    add("### Viewer")
    add("")
    add("`figures/viewer.html` — one self-contained page, 3Dmol.js pinned at 2.0.4 from "
        "cdnjs, with the receptor PDB, ligand SDF and pocket JSON inlined, so it needs no "
        "server, no Jupyter kernel and no browser file-access flags.")
    add("")
    add("```")
    add("start figures\\viewer.html        # Windows cmd / PowerShell")
    add("```")
    add("")
    add("Receptor = spectrum cartoon, erlotinib = cyan sticks, the 20 residues within "
        "5 Å = yellow sticks. Controls: switch 1M17 ↔ 4HJO, whole-domain vs pocket zoom, "
        "residue labels, the 5 Å docking box, pocket surface. Rendering verified in "
        "headless Chromium (canvas present, no page errors). Reference captures: "
        "`figures/egfr_1M17_viewer.png` and `figures/egfr_4HJO_viewer.png` (whole "
        "domain), `figures/egfr_1M17_pocket.png` (pocket zoom with residue labels — "
        "the one to use in the proposal).")
    add("")
    add("---")
    add("")
    add("## 7. Reproducibility evidence")
    add("")
    repro = paths.RESULTS / "reproducibility.json"
    if repro.exists():
        checks = load_json(repro)
        env = checks["environment"]
        add("`src/08_verify_repro.py --with-rf` snapshots the SHA-256 of every artefact, "
            "re-runs " + ", ".join(f"`{s}`" for s in checks["scripts_rerun"])
            + " and diffs. Result: "
            f"**{checks['n_identical']}/{checks['n_artefacts']} artefacts byte-identical**, "
            "including `baseline_metrics.csv` after all 120 forest refits.")
        add("")
        add("| artefact | check | result |")
        add("| --- | --- | --- |")
        for c in checks["checks"]:
            add(f"| `{c['artefact']}` | {c['check']} | {c['result']} |")
        add("")
        add(f"Verified on {checks['date']} with `{env['interpreter']}` "
            f"(Python {env['python']}, rdkit {env['rdkit']}, "
            f"scikit-learn {env['scikit-learn']}, pandas {env['pandas']}, "
            f"numpy {env['numpy']}).")
        if "venv-check" in env["interpreter"]:
            add("")
            add("That interpreter is a **throwaway virtualenv built from "
                "`requirements.txt` alone** (`pip install --no-deps -r requirements.txt`), "
                "and `data/raw/` had been deleted and re-downloaded from TDC beforehand — "
                "so the identical hashes cover a clean-slate rebuild of the environment "
                "and the data, not just a re-run in place.")
    else:
        add("Run `src/08_verify_repro.py --with-rf` to generate "
            "`results/reproducibility.json`.")
    add("")
    add("---")
    add("")
    add("## 8. Known limitations to state in the proposal")
    add("")
    add("1. Stereochemistry is dropped (v1 simplification, Section 3).")
    add(f"2. Labels are sparse: each endpoint covers "
        f"{clean_stats['n_tested'].min()}–{clean_stats['n_tested'].max()} of the "
        f"{std['final_molecules']} molecules; models are per-endpoint with no multi-task "
        "sharing yet.")
    add(f"3. Classes are imbalanced ({clean_stats['positive_rate'].min():.1%}–"
        f"{clean_stats['positive_rate'].max():.1%} positives); `class_weight=\"balanced\"` "
        "is the only mitigation and PR-AUC is the more honest metric.")
    add("4. Binding affinity is not modelled yet — Task 5 only prepares the receptor, "
        "pocket box and viewer that the docking/affinity stage will consume.")
    add("5. The scaffold split uses one global greedy pass; it is not balanced per "
        "endpoint, so individual endpoints can have very different positive rates "
        "between train and test.")
    add("")

    text = "\n".join(L) + "\n"
    out = paths.ROOT / "RESULTS.md"
    out.write_text(text, encoding="utf-8")
    print(f"Wrote {out} ({len(text) / 1024:.1f} KB, {len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
