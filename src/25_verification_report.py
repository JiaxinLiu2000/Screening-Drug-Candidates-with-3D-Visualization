"""Generate VERIFICATION.md - the data-integrity report for the whole project.

Answers one question: is every committed number trustworthy? It collects the
three independent lines of evidence already produced by the pipeline -

    1. cross-artefact integrity checks (src/15_data_audit.py)
    2. byte-level reproduction of every artefact (src/08_verify_repro.py)
    3. the measured values themselves, phase by phase

- and lists, explicitly, what the verification does NOT cover. Nothing is
recomputed here; every figure is read back from a committed artefact.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tox21lib import paths  # noqa: E402

PROVENANCE_PATHS = ("src", "results", "splits", "receptors")


def load(name: str) -> dict:
    path = paths.RESULTS / name
    if not path.exists():
        raise SystemExit(f"FAILED: {path} missing - run the pipeline first")
    return json.loads(path.read_text(encoding="utf-8"))


def git_commit() -> str:
    try:
        def git(*args: str) -> str:
            out = subprocess.run(["git", *args], cwd=paths.ROOT,
                                 capture_output=True, text=True, check=True)
            return out.stdout.strip()

        commit = git("log", "-1", "--format=%h", "--abbrev=7", "--", *PROVENANCE_PATHS)
        dirty = git("status", "--porcelain", "--", *PROVENANCE_PATHS)
        return f"{commit}-dirty" if dirty else commit
    except Exception:  # noqa: BLE001
        return "n/a"


def main() -> int:
    audit = load("data_audit.json")
    repro = load("reproducibility.json")
    std = load("standardization_stats.json")
    scaf = load("scaffold_stats.json")
    chem_davis = load("chemical_space_overlap.json")
    chem_kiba = load("chemical_space_overlap_kiba.json")
    herg = load("herg_large_stats.json")
    bench2 = load("docking_benchmark_v2.json")
    attrib = load("attribution.json")
    reliability = load("endpoint_reliability.json")
    ablation = load("shared_encoder_ablation.json")
    binding_stats = load("binding_dataset_stats.json")

    summary = pd.read_csv(paths.RESULTS / "baseline_summary.csv")
    metrics = pd.read_csv(paths.RESULTS / "baseline_metrics.csv")
    binding = pd.read_csv(paths.RESULTS / "binding_baseline.csv")
    neural = pd.read_csv(paths.RESULTS / "shared_encoder_metrics.csv")
    overall = summary[summary["level"] == "overall"]
    tox = overall[overall["dataset"] == "Tox21"].set_index("split")
    hl = overall[overall["dataset"] == "hERG-large"].set_index(["setting", "split"])
    tox_drop = float(tox.loc["random", "roc_auc_mean"] - tox.loc["scaffold", "roc_auc_mean"])
    diff_ci = reliability["difference_random_minus_scaffold"]["roc_auc"]["ci"]

    nn_k = chem_kiba["nn_tanimoto"]
    bench_recs = [
        json.loads(p.read_text(encoding="utf-8"))
        for p in sorted((paths.RECEPTORS / "benchmark_v2").glob("*.json"))
    ]
    n_active = sum(1 for r in bench_recs if r["conformation"]["distance_angstrom"] <= 4.0)

    L: list[str] = []
    add = L.append

    add("# Data verification")
    add("")
    add(f"Every committed number in this project, and the evidence that it is "
        f"trustworthy. Generated by `src/25_verification_report.py` from the "
        f"committed artefacts; nothing here is recomputed or estimated.")
    add("")
    add(f"- commit: `{git_commit()}`")
    add(f"- verified on {audit.get('date', repro['date'])} with "
        f"`{repro['environment']['interpreter']}` (Python "
        f"{repro['environment']['python']}, rdkit {repro['environment']['rdkit']}, "
        f"scikit-learn {repro['environment']['scikit-learn']})")
    add("")
    add("## Verdict")
    add("")
    status = "PASS" if audit["n_fail"] == 0 and not repro["differing"] else "FAIL"
    add(f"**{status}.** {audit['n_pass']}/{len(audit['checks'])} integrity checks pass "
        f"and {repro['n_identical']}/{repro['n_artefacts']} artefacts reproduce "
        f"byte-identically from a clean re-run.")
    add("")

    add("## 1. Cross-artefact integrity checks")
    add("")
    add("These do not trust any script's own assertions: each recomputes a quantity "
        "from the artefact it is derived from and compares. A check that matches "
        "nothing fails rather than passing vacuously.")
    add("")
    add("| area | checks | result |")
    add("| --- | --- | --- |")
    by_section: dict[str, list[dict]] = {}
    for c in audit["checks"]:
        by_section.setdefault(c["section"], []).append(c)
    for section, items in by_section.items():
        n_fail = sum(1 for i in items if i["status"] == "FAIL")
        verdict = "all pass" if n_fail == 0 else f"**{n_fail} FAILED**"
        add(f"| {section} | {len(items)} | {verdict} |")
    add(f"| **total** | **{len(audit['checks'])}** | "
        f"**{audit['n_pass']} pass, {audit['n_fail']} fail, {audit['n_skip']} skip** |")
    add("")
    add("The strongest of them, in the sense that they would catch a silent "
        "corruption rather than a missing file:")
    add("")
    highlights = [
        "summary mean/std recompute exactly from the per-fit rows",
        "pocket centre and box recompute from the ligand coordinates",
        "median nearest-neighbour Tanimoto recomputes to the reported value",
        "cold splits leak no entity between train and valid/test",
        "reported means recompute from the per-run table",
        "the group-masking control agrees with the per-atom result",
    ]
    add("| check | measured |")
    add("| --- | --- |")
    for c in audit["checks"]:
        if c["name"] in highlights:
            add(f"| {c['name']} | {c['detail']} |")
    add("")
    add("Full list: [`results/DATA_AUDIT.md`](results/DATA_AUDIT.md).")
    add("")

    add("## 2. Byte-level reproduction")
    add("")
    add(f"`src/08_verify_repro.py --with-rf` snapshots the SHA-256 of every artefact, "
        f"re-runs {', '.join('`' + s + '`' for s in repro['scripts_rerun'])}, and "
        f"diffs. Result: **{repro['n_identical']}/{repro['n_artefacts']} identical**, "
        f"including the 120 Tox21 forest fits and the 30 hERG/hERG-large fits.")
    add("")
    add("| artefact group | result |")
    add("| --- | --- |")
    for c in repro["checks"]:
        add(f"| {c['artefact']} | {c['result']} |")
    add("")
    add("Two sources of run-to-run drift were found and removed rather than tolerated: "
        "sklearn's forests accumulate per-tree probabilities across threads, so metric "
        "tables are written at 10 decimal places (six beyond anything reported); and "
        "`04_baseline_rf.py` rewrites the shared tables from scratch, so the verifier "
        "re-runs every script that appends to them, in order.")
    add("")

    add("## 3. The measured values")
    add("")
    add("### Dataset construction")
    add("")
    add("| quantity | value |")
    add("| --- | --- |")
    add(f"| Tox21 molecules after standardization + dedup | **{std['final_molecules']}** |")
    add(f"| from | {std['input_rows']} merged rows, {std['parse_failures']} unparsable, "
        f"{std['duplicate_rows_merged']} duplicates merged, {std['filtered_out']} filtered |")
    add(f"| unique Bemis-Murcko scaffolds | {scaf['n_unique_scaffolds']} "
        f"(largest group {scaf['largest_group_size']}) |")
    add(f"| hERG-large (Karim) | {herg['full_molecules']} molecules, "
        f"{herg['disjoint_removed']} shared with Tox21 → "
        f"{herg['disjoint_molecules']} in the Disjoint setting |")
    add(f"| KIBA | {binding_stats['KIBA']['distinct_drugs']} drugs × "
        f"{binding_stats['KIBA']['distinct_proteins']} proteins, "
        f"{binding_stats['KIBA']['measured_pairs']} pairs |")
    add(f"| Davis | {binding_stats['DAVIS']['distinct_drugs']} drugs × "
        f"{binding_stats['DAVIS']['distinct_proteins']} proteins, "
        f"{binding_stats['DAVIS']['final_pairs_at_ceiling_kd_10000nM']} of "
        f"{binding_stats['DAVIS']['measured_pairs']} pairs at the censored ceiling |")
    add("")

    add("### Toxicity baselines (random forest)")
    add("")
    add("| dataset | setting | random | scaffold | drop |")
    add("| --- | --- | --- | --- | --- |")
    for (dataset, setting), group in overall.groupby(["dataset", "setting"]):
        g = group.set_index("split")
        if not {"random", "scaffold"} <= set(g.index):
            continue
        r, s = g.loc["random"], g.loc["scaffold"]
        add(f"| {dataset} | {setting} | {r['roc_auc_mean']:.4f} ± {r['roc_auc_std']:.4f} "
            f"| {s['roc_auc_mean']:.4f} ± {s['roc_auc_std']:.4f} "
            f"| {r['roc_auc_mean'] - s['roc_auc_mean']:+.4f} |")
    add("")
    add(f"The Tox21 scaffold-split penalty of {tox_drop:.4f} carries a paired bootstrap "
        f"95% CI of [{diff_ci[0]:.4f}, {diff_ci[1]:.4f}] over 1000 resamples per fold, "
        f"excluding zero. {len(reliability['flagged'])} endpoint/split combinations hold "
        f"fewer than 20 test positives in at least one seed and are not interpreted "
        f"individually.")
    add("")

    add("### Binding baselines (random forest)")
    add("")
    add("| dataset | split | test drugs | Pearson r |")
    add("| --- | --- | --- | --- |")
    for (dataset, split), g in binding.groupby(["dataset", "split"]):
        add(f"| {dataset} | {split} | {g['n_test_drugs'].mean():.0f} "
            f"| {g['pearson_r'].mean():.4f} ± {g['pearson_r'].std(ddof=1):.4f} |")
    add("")

    add("### Shared-encoder ablation")
    add("")
    add(f"{len(neural)} runs, {neural['train_seconds'].sum() / 3600:.1f} GPU-hours. "
        f"Verdict: **{ablation['verdict']}**.")
    add("")
    add("| comparison | toxicity macro ROC-AUC | affinity Pearson r |")
    add("| --- | --- | --- |")
    add(f"| effect of sharing, from scratch | "
        f"{ablation['effect_of_sharing_scratch_tox']:+.4f} | "
        f"{ablation['effect_of_sharing_scratch_affinity']:+.4f} |")
    add(f"| effect of sharing, best loss weight | "
        f"{ablation['effect_of_sharing_best_weight_tox']:+.4f} | "
        f"{ablation['effect_of_sharing_best_weight_affinity']:+.4f} |")
    add(f"| effect of sharing, pretrained | "
        f"{ablation['effect_of_sharing_pretrained_tox']:+.4f} | "
        f"{ablation['effect_of_sharing_pretrained_affinity']:+.4f} |")
    add(f"| seed-to-seed noise floor | {ablation['tox_noise_floor']:.4f} "
        f"| {ablation['affinity_noise_floor']:.4f} |")
    add("")

    add("### Chemical space and structures")
    add("")
    add("| quantity | value |")
    add("| --- | --- |")
    add(f"| Tox21 → KIBA median nearest-neighbour Tanimoto | "
        f"**{nn_k['tox21_to_kiba']['median']:.4f}** ({chem_kiba['verdict'].lower()}) |")
    add(f"| calibration: within Tox21 / within KIBA | "
        f"{nn_k['within_tox21']['median']:.4f} / {nn_k['within_kiba']['median']:.4f} |")
    add(f"| superseded Davis measurement | "
        f"{chem_davis['nn_tanimoto']['tox21_to_davis']['median']:.4f} "
        f"({chem_davis['verdict'].lower()}, 68 drugs) |")
    add(f"| docking benchmark v2 | {len(bench_recs)} structures, {n_active} active / "
        f"{len(bench_recs) - n_active} inactive, median pairwise ligand Tanimoto "
        f"{bench2['similarity']['median']:.3f} |")
    add(f"| attribution: top-{attrib['top_k']} atoms hit the alert | "
        f"{attrib['top_hits_alert_rate']:.1%} of {attrib['n_with_alerts']} molecules |")
    add(f"| attribution control: whole alert beats a random same-size set | "
        f"{attrib['control']['beats_null_rate']:.1%} of "
        f"{attrib['control']['n_molecules']} molecules |")
    add("")

    add("## 4. What this verification does NOT cover")
    add("")
    add("Stating the limits is part of the verification; a check that is not run is "
        "not a check that passed.")
    add("")
    add("- **External validity.** Every number is measured on these datasets with "
        "these splits. Nothing here says the models generalise to new chemistry "
        "beyond what the scaffold split already probes.")
    add("- **Bootstrap scope.** The endpoint confidence intervals resample test "
        "molecules only. They do not include retraining variance or the variance of "
        "choosing a different split protocol.")
    add("- **Neural training budget.** Configurations D, E and F hit their epoch cap "
        "in every run, so their numbers are a lower bound and any comparison against "
        "the uncapped GIN configurations is budget-mismatched.")
    add("- **Loss-weight grid.** 2 seeds per cell for most weights; for the "
        "pretrained encoder the seed spread exceeds the weight spread, so the grid "
        "bounds the effect rather than locating an optimum.")
    add("- **Docking.** No docking has been run. The benchmark is assembled and "
        "documented only, and its active structures are systematically lower "
        "resolution than its inactive ones.")
    add("- **Attribution ground truth.** There is none. The structural-alert "
        "comparison is a proxy, validated against a random same-size-group null.")
    add("- **Stereochemistry.** Dropped in v1 standardization, so stereo-dependent "
        "toxicity cannot be expressed by any model here.")
    add("")
    add("## Where to read more")
    add("")
    add("| document | contents |")
    add("| --- | --- |")
    for doc, what in [
        ("RESULTS.md", "every Phase 1 measurement, with the Phase 2/3 index"),
        ("results/SUMMARY.md", "the four proposal values"),
        ("results/PHASE2_DECISIONS.md", "the five Phase 2 go/no-go decisions"),
        ("results/PHASE3_DECISIONS.md", "the six Phase 3 decisions"),
        ("results/DATA_AUDIT.md", "all integrity checks, one row each"),
        ("results/shared_encoder_ablation.md", "the four-way ablation and loss-weight grid"),
        ("results/attribution.md", "atom attribution, the control, and failure cases"),
    ]:
        add(f"| [`{doc}`]({doc}) | {what} |")
    add("")

    text = "\n".join(L) + "\n"
    out = paths.ROOT / "VERIFICATION.md"
    out.write_text(text, encoding="utf-8")
    print(text)
    print(f"[wrote {out}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
