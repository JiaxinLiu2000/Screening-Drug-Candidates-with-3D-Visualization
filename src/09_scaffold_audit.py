"""Phase 2 Task 1 - audit the Murcko scaffold variant used by the scaffold split.

Compares RDKit's chemically-aware Bemis-Murcko scaffold (``GetScaffoldForMol``,
used by ``tox21lib.splits.scaffold_smiles`` -> ``03_splits.py``) with the generic
framework (``MakeScaffoldGeneric``) on the same 6143 standardized molecules.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pandas as pd

from tox21lib import paths
from tox21lib import splits as splitlib

TOP_K = 10
VARIANTS = {
    "murcko": ("Bemis-Murcko (GetScaffoldForMol) - used by 03_splits.py", splitlib.scaffold_smiles),
    "generic": ("Generic framework (MakeScaffoldGeneric)", splitlib.generic_scaffold_smiles),
}


def group_counts(scaffolds: pd.Series) -> pd.DataFrame:
    counts = scaffolds.value_counts().rename_axis("scaffold").reset_index(name="n")
    # deterministic: size desc, then SMILES asc
    return counts.sort_values(["n", "scaffold"], ascending=[False, True], kind="mergesort").reset_index(drop=True)


def stats_for(scaffolds: pd.Series) -> dict:
    counts = group_counts(scaffolds)
    return {
        "n_molecules": int(len(scaffolds)),
        "n_unique_scaffolds": int(len(counts)),
        "largest_group_size": int(counts.loc[0, "n"]),
        "largest_group_scaffold": str(counts.loc[0, "scaffold"]),
        "n_singleton_scaffolds": int((counts["n"] == 1).sum()),
        "n_acyclic_molecules": int((scaffolds == "").sum()),
        "top10": [
            {"rank": i + 1, "scaffold": str(r.scaffold), "n": int(r.n)}
            for i, r in enumerate(counts.head(TOP_K).itertuples())
        ],
    }


def membership_changes(a: pd.Series, b: pd.Series) -> int:
    """Molecules whose set of co-members differs between the two groupings."""
    ga = a.groupby(a).ngroup()
    gb = b.groupby(b).ngroup()
    pair = pd.DataFrame({"a": ga.to_numpy(), "b": gb.to_numpy()})
    size_a = pair.groupby("a")["a"].transform("size")
    size_b = pair.groupby("b")["b"].transform("size")
    size_ab = pair.groupby(["a", "b"])["a"].transform("size")
    same = (size_ab == size_a) & (size_ab == size_b)
    return int((~same).sum())


def fmt(s: str) -> str:
    return "`<acyclic>`" if s == "" else f"`{s}`"


def main() -> int:
    clean = pd.read_parquet(paths.CLEAN_PARQUET)
    smiles = clean["canonical_smiles"].tolist()
    scaf = {k: pd.Series([fn(s) for s in smiles], name=k) for k, (_, fn) in VARIANTS.items()}
    stats = {k: stats_for(v) for k, v in scaf.items()}

    n_changed = membership_changes(scaf["murcko"], scaf["generic"])
    ratio = stats["generic"]["n_unique_scaffolds"] / stats["murcko"]["n_unique_scaffolds"]

    out = {
        "variant_used_by_03_splits": "murcko",
        "evidence": "src/tox21lib/splits.py:28 scaffold_smiles() calls MurckoScaffold.GetScaffoldForMol(mol)",
        "variants": stats,
        "n_molecules_changing_group_membership": n_changed,
        "generic_over_murcko_group_count_ratio": round(ratio, 6),
        "rf_baseline_rerun_required": False,
        "recommendation": "murcko",
    }
    paths.RESULTS.mkdir(parents=True, exist_ok=True)
    (paths.RESULTS / "scaffold_audit.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")

    m, g = stats["murcko"], stats["generic"]
    L = [
        "# Scaffold audit (Phase 2, Task 1)",
        "",
        f"Molecules: {m['n_molecules']} (from `data/processed/tox21_clean.parquet`). "
        "Generated by `src/09_scaffold_audit.py`.",
        "",
        "## Which variant does the scaffold split use?",
        "",
        "**Chemically-aware Bemis-Murcko scaffold** (atom identity and bond orders kept). "
        "Evidence: `src/tox21lib/splits.py` line 28, inside `scaffold_smiles()`, calls "
        "`MurckoScaffold.GetScaffoldForMol(mol)`; `src/03_splits.py` line 30 builds the split from "
        "`splitlib.scaffold_smiles`. `MakeScaffoldGeneric` is not used anywhere in the split path.",
        "",
        "## Summary statistics",
        "",
        "| Statistic | Bemis-Murcko (used) | Generic framework |",
        "|---|---|---|",
        f"| Unique scaffolds | {m['n_unique_scaffolds']} | {g['n_unique_scaffolds']} |",
        f"| Largest group size | {m['largest_group_size']} | {g['largest_group_size']} |",
        f"| Largest group scaffold | {fmt(m['largest_group_scaffold'])} | {fmt(g['largest_group_scaffold'])} |",
        f"| Singleton scaffolds | {m['n_singleton_scaffolds']} | {g['n_singleton_scaffolds']} |",
        f"| Acyclic molecules (empty scaffold) | {m['n_acyclic_molecules']} | {g['n_acyclic_molecules']} |",
        "",
        f"- Molecules whose scaffold-group membership changes between variants: **{n_changed}** "
        f"of {m['n_molecules']}.",
        f"- Group-count ratio generic / Murcko: **{ratio:.4f}** "
        f"({g['n_unique_scaffolds']} / {m['n_unique_scaffolds']}).",
        "",
        "## Ten largest groups",
        "",
        "| Rank | Bemis-Murcko scaffold | n | Generic scaffold | n |",
        "|---|---|---|---|---|",
    ]
    for a, b in zip(m["top10"], g["top10"]):
        L.append(f"| {a['rank']} | {fmt(a['scaffold'])} | {a['n']} | {fmt(b['scaffold'])} | {b['n']} |")
    L += [
        "",
        "## Recommendation",
        "",
        "Keep the chemically-aware Bemis-Murcko scaffold (`GetScaffoldForMol`) as the standard scaffold split; "
        "the generic framework may be reported only as an additional, harsher stress test.",
        "",
        "## Materiality verdict",
        "",
        "**No correction needed.** The split already uses the non-generic Bemis-Murcko variant, so the quoted "
        "scaffold-split ROC-AUC of 0.761 (0.7611 +/- 0.0227) stands as computed and the RF baseline does not need "
        "re-running. The generic framework only merges Murcko groups (fewer, larger groups, "
        f"{g['n_unique_scaffolds']} vs {m['n_unique_scaffolds']}), which would make train/test chemically more "
        "distant, i.e. a harsher split, not a correction of an error.",
        "",
    ]
    (paths.RESULTS / "scaffold_audit.md").write_text("\n".join(L), encoding="utf-8")

    print(json.dumps({k: v for k, v in out.items() if k != "variants"}, indent=2))
    for k in ("murcko", "generic"):
        s = stats[k]
        print(k, s["n_unique_scaffolds"], s["largest_group_size"], repr(s["largest_group_scaffold"]), s["n_singleton_scaffolds"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
