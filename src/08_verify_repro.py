"""Verify the pipeline re-runs to identical results, by hash, not by eyeball.

Snapshots the SHA-256 of every committed artefact, re-runs scripts 02-05 with the
current interpreter, and compares. Writes results/reproducibility.json, which
`src/07_report.py` folds into RESULTS.md.

    python src/08_verify_repro.py              # re-run 02,03,05 (fast, ~1 min)
    python src/08_verify_repro.py --with-rf    # also re-run 04 (adds ~4 min)

Run it with a freshly built virtualenv to check the environment too; the
interpreter path and package versions are recorded in the JSON.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tox21lib import paths  # noqa: E402

SRC = Path(__file__).resolve().parent


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def snapshot(files: list[Path]) -> dict[str, str]:
    """SHA-256 per artefact, keyed by POSIX-style relative path.

    Keys are normalised so group lookups never silently miss on Windows
    backslashes and report "nothing compared" as a pass.
    """
    return {
        p.relative_to(paths.ROOT).as_posix(): sha256(p) for p in files if p.exists()
    }


def artefacts(with_rf: bool) -> dict[str, list[Path]]:
    """Artefacts regenerated by the scripts this verifier re-runs, by group.

    Only the artefacts actually rewritten here are tracked. `splits/davis_*`,
    `splits/kiba_*` and `receptors/benchmark/` come from `11_binding_baseline.py`
    and `13_docking_benchmark.py`, which this verifier does not re-run, so
    including them would assert nothing.
    """
    groups: dict[str, list[Path]] = {
        "Tox21 split index files": sorted(
            list(paths.SPLITS.glob("random_split_seed*.csv"))
            + list(paths.SPLITS.glob("scaffold_split_seed*.csv"))
            + [paths.SPLITS / "scaffolds.csv"]
        ),
        "cleaned molecule table": [paths.CLEAN_PARQUET],
        "standardization + split stats": [
            paths.RESULTS / "standardization_stats.json",
            paths.RESULTS / "scaffold_stats.json",
            paths.RESULTS / "split_sizes.csv",
            paths.RESULTS / "clean_endpoint_stats.csv",
            paths.RESULTS / "split_seed_overlap.csv",
        ],
        "EGFR receptors, ligand SDFs, pocket JSON": sorted(
            p for p in paths.RECEPTORS.iterdir() if p.is_file()
        ),
    }
    if with_rf:
        groups["Tox21 + hERG metric tables"] = [
            paths.RESULTS / "baseline_metrics.csv",
            paths.RESULTS / "baseline_summary.csv",
        ]
        groups["hERG split index files"] = sorted(
            paths.SPLITS.glob("herg_*_split_seed*.csv")
        )
        groups["hERG stats"] = [paths.RESULTS / "herg_stats.json"]
    return groups


def run(script: str) -> None:
    print(f"  $ python src/{script}")
    proc = subprocess.run(
        [sys.executable, "-W", "ignore", str(SRC / script)],
        cwd=paths.ROOT,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        print(proc.stdout[-3000:])
        print(proc.stderr[-3000:])
        raise SystemExit(f"FAILED: src/{script} exited {proc.returncode}")


def versions() -> dict[str, str]:
    import numpy
    import pandas
    import rdkit
    import sklearn

    out = {
        "python": sys.version.split()[0],
        "interpreter": sys.executable,
        "rdkit": rdkit.__version__,
        "scikit-learn": sklearn.__version__,
        "pandas": pandas.__version__,
        "numpy": numpy.__version__,
    }
    try:
        import gemmi

        out["gemmi"] = gemmi.__version__
    except Exception:  # noqa: BLE001
        pass
    return out


def main() -> int:
    with_rf = "--with-rf" in sys.argv
    groups = artefacts(with_rf)
    tracked = [p for files in groups.values() for p in files]
    missing = [p for p in tracked if not p.exists()]
    if missing:
        raise SystemExit(
            "FAILED: run the pipeline before verifying it; missing "
            + ", ".join(str(p.relative_to(paths.ROOT)) for p in missing)
        )

    print(f"Snapshotting {len(tracked)} artefact hashes in {len(groups)} groups...")
    before = snapshot(tracked)

    scripts = ["02_standardize.py", "03_splits.py"]
    if with_rf:
        # 04 rewrites results/baseline_metrics.csv and baseline_summary.csv from
        # scratch (Tox21 only), so the hERG external check must re-append its rows
        # immediately afterwards or the committed tables lose them. 12 is
        # idempotent: it replaces its own hERG rows rather than duplicating them.
        scripts += ["04_baseline_rf.py", "12_herg_baseline.py"]
    scripts.append("05_egfr_structure.py")

    print(f"Re-running {len(scripts)} scripts with {sys.executable}")
    for script in scripts:
        run(script)

    after = snapshot(tracked)

    identical = sorted(k for k in before if before[k] == after.get(k))
    differing = sorted(k for k in before if before[k] != after.get(k))

    print(f"\nidentical: {len(identical)}/{len(before)}")
    for k in differing:
        print(f"  DIFFERS: {k}")

    failures: list[str] = []
    checks = []
    for label, files in groups.items():
        keys = [p.relative_to(paths.ROOT).as_posix() for p in files]
        if not keys:
            # An empty group would make the comparison below vacuously true.
            failures.append(f"{label}: no artefacts matched")
            result = "FAILED: no artefacts matched"
        else:
            bad = [k for k in keys if before.get(k) != after.get(k)]
            if bad:
                failures.append(f"{label}: {len(bad)} artefact(s) changed")
                result = f"DIFFERS: {bad}"
            else:
                noun = "file" if len(keys) == 1 else "files"
                result = f"identical ({len(keys)} {noun})"
        checks.append(
            {
                "artefact": label,
                "n_files": len(keys),
                "check": "SHA-256 before vs after re-running "
                         + ", ".join(s.split("_")[0] for s in scripts),
                "result": result,
            }
        )

    payload = {
        "date": date.today().isoformat(),
        "scripts_rerun": scripts,
        "environment": versions(),
        "n_artefacts": len(before),
        "n_identical": len(identical),
        "differing": differing,
        "group_failures": failures,
        "checks": checks,
        "hashes": after,
    }
    out = paths.RESULTS / "reproducibility.json"
    out.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"\nWrote {out}")
    for f in failures:
        print(f"  FAILED: {f}")
    return 1 if (differing or failures) else 0


if __name__ == "__main__":
    raise SystemExit(main())
